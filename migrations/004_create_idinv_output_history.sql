-- リスト出力履歴テーブル
CREATE TABLE NAM_IAM_ADMIN.IDINV_OUTPUT_HISTORY (
    OUTPUT_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    OUTPUT_TYPE VARCHAR2(50) NOT NULL,
    OUTPUT_DATETIME TIMESTAMP DEFAULT SYSTIMESTAMP,
    OUTPUT_USER VARCHAR2(50),

    -- 対象日
    TARGET_DATE DATE,
    TARGET_MONTH VARCHAR2(7),

    -- 出力結果
    SPREADSHEET_URL VARCHAR2(500),
    STATUS VARCHAR2(20),
    TOTAL_SYSTEMS NUMBER(5),
    TOTAL_USERS NUMBER(10),
    ERROR_MESSAGE CLOB,

    -- システム項目
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

COMMENT ON TABLE NAM_IAM_ADMIN.IDINV_OUTPUT_HISTORY IS 'リスト出力履歴';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_OUTPUT_HISTORY.OUTPUT_TYPE IS '出力種別（TANAOROSHI, TAISHOKU, TENSHUTU）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_OUTPUT_HISTORY.TARGET_MONTH IS '対象月（YYYY-MM）';
