-- 組織変更テーブル
CREATE TABLE NAM_IAM_ADMIN.IDINV_ORGANIZATION_CHANGES (
    CHANGE_DATE DATE NOT NULL,
    BEFORE_ORG_CD VARCHAR2(10) NOT NULL,
    BEFORE_ORG_NAME VARCHAR2(200),
    AFTER_ORG_CD VARCHAR2(10) NOT NULL,
    AFTER_ORG_NAME VARCHAR2(200),
    REMARKS VARCHAR2(1000),

    PRIMARY KEY (CHANGE_DATE, BEFORE_ORG_CD, AFTER_ORG_CD)
);

COMMENT ON TABLE NAM_IAM_ADMIN.IDINV_ORGANIZATION_CHANGES IS '組織変更情報';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_ORGANIZATION_CHANGES.CHANGE_DATE IS '変更日';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_ORGANIZATION_CHANGES.BEFORE_ORG_CD IS '変更前組織コード';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_ORGANIZATION_CHANGES.BEFORE_ORG_NAME IS '変更前組織名';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_ORGANIZATION_CHANGES.AFTER_ORG_CD IS '変更後組織コード';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_ORGANIZATION_CHANGES.AFTER_ORG_NAME IS '変更後組織名';
