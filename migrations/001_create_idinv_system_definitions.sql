-- システムユーザー情報定義テーブル
-- ※ 後続マイグレーション（006/010/012/013/add_sort_sql/alter_output_columns）の
--    カラム追加・削除を反映した最新の完全定義。新規構築時はこのファイルを実行すれば足りる。
CREATE TABLE NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS (
    -- 基本情報
    SYSTEM_ID VARCHAR2(50) PRIMARY KEY,
    SYSTEM_NAME VARCHAR2(200) NOT NULL,
    DESCRIPTION VARCHAR2(500),

    -- 取り込み設定
    IMPORT_METHOD VARCHAR2(20),
    IMPORT_TABLE_NAME CLOB,
    IMPORT_MAPPING_JSON CLOB,
    LAST_IMPORT_DATETIME TIMESTAMP,
    LAST_IMPORT_USER VARCHAR2(50),
    LAST_IMPORT_RECORD_COUNT NUMBER(10),

    -- 共通出力設定
    OUTPUT_REQUIRED NUMBER(1) DEFAULT 1,
    OUTPUT_ORDER NUMBER(3),
    OUTPUT_SHEET_NAME VARCHAR2(100),

    -- ユーザー棚卸リスト設定
    TANAOROSHI_OUTPUT_COLUMNS_JSON CLOB,
    TANAOROSHI_OUTPUT_MODE VARCHAR2(20) DEFAULT 'MISMATCH_ONLY',
    TANAOROSHI_FILTER_SQL CLOB,
    TANAOROSHI_SORT_SQL CLOB,

    -- 組織転出者リスト設定
    TENSHUTU_OUTPUT_COLUMNS_JSON CLOB,
    TENSHUTU_FILTER_SQL CLOB,
    TENSHUTU_SORT_SQL CLOB,

    -- 退職者ID削除依頼書設定
    TAISHOKU_OUTPUT_REQUIRED NUMBER(1) DEFAULT 1,
    TAISHOKU_OUTPUT_ORDER NUMBER(3),
    TAISHOKU_DISPLAY_SQL CLOB,
    TAISHOKU_DISABLED_EXPRESSION VARCHAR2(500),

    -- 確認情報
    CHECK_FREQUENCY VARCHAR2(20) DEFAULT 'MONTHLY',
    CHECK_RESPONSIBLE VARCHAR2(50),
    OUTPUT_SCOPE VARCHAR2(500),
    CHECK_POINTS VARCHAR2(500),
    CHECK_REMARKS VARCHAR2(500),

    -- 状態管理
    IS_ACTIVE NUMBER(1) DEFAULT 1,
    REMARKS VARCHAR2(1000),

    -- システム項目
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CREATED_BY VARCHAR2(50),
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_BY VARCHAR2(50)
);

COMMENT ON TABLE NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS IS '各システムのユーザー情報定義マスタ';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.SYSTEM_ID IS 'システムID（一意識別子）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.SYSTEM_NAME IS 'システム名';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.IMPORT_METHOD IS '取り込み方法（CSV, XLSX, DIRECT）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.IMPORT_TABLE_NAME IS '取り込み先テーブル名 または 参照SQL（SELECT/WITHで始まる場合はSQL、それ以外はテーブル名）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.OUTPUT_REQUIRED IS '出力要否（0:不要、1:必要）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TANAOROSHI_OUTPUT_COLUMNS_JSON IS '棚卸リスト出力項目定義（JSON形式）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TANAOROSHI_OUTPUT_MODE IS '棚卸出力モード（ALL, MISMATCH_ONLY, CUSTOM）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TANAOROSHI_FILTER_SQL IS '棚卸リストフィルタSQL（WHERE句、s.カラム名で参照）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TANAOROSHI_SORT_SQL IS '棚卸リスト出力ソート順（例: z.SHOZOKU ASC, s.USER_CD ASC）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TENSHUTU_OUTPUT_COLUMNS_JSON IS '組織転出者リスト出力項目定義（JSON形式）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TENSHUTU_FILTER_SQL IS '転出者リストフィルタSQL（WHERE句、s.カラム名で参照）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TENSHUTU_SORT_SQL IS '転出者リスト出力ソート順（例: t.BEFORE_ORG ASC, s.USER_CD ASC）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TAISHOKU_DISPLAY_SQL IS '退職者リスト表示SQL（SELECT句の1列分、テーブルエイリアスはs）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.TAISHOKU_DISABLED_EXPRESSION IS '退職者ID削除依頼書で無効化済み判定を行う条件式（例: S.ACCOUNT_STATUS IN (''Disabled'', ''Suspended'')）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.CHECK_FREQUENCY IS '確認頻度（MONTHLY: 月次, ANNUAL: 年次5月）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.CHECK_RESPONSIBLE IS '確認担当者のユーザーID';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.OUTPUT_SCOPE IS '出力範囲（自由入力）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.CHECK_POINTS IS '確認ポイント（自由入力）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.CHECK_REMARKS IS '確認に関する備考（自由入力）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS.IS_ACTIVE IS '有効フラグ（0:無効、1:有効）';
