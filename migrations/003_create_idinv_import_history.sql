-- 取り込み履歴テーブル
CREATE TABLE NAM_IAM_ADMIN.IDINV_IMPORT_HISTORY (
    BATCH_ID VARCHAR2(50) PRIMARY KEY,
    SYSTEM_ID VARCHAR2(50) NOT NULL,
    IMPORT_DATETIME TIMESTAMP DEFAULT SYSTIMESTAMP,
    IMPORT_USER VARCHAR2(50),

    -- ファイル情報
    FILE_NAME VARCHAR2(500),
    FILE_SIZE NUMBER(15),
    FILE_HASH VARCHAR2(64),

    -- 処理結果
    STATUS VARCHAR2(20),
    TOTAL_RECORDS NUMBER(10),
    SUCCESS_RECORDS NUMBER(10),
    ERROR_RECORDS NUMBER(10),
    ERROR_MESSAGE CLOB,

    -- 処理時間
    START_TIME TIMESTAMP,
    END_TIME TIMESTAMP,

    CONSTRAINT IDINV_FK_IMPORT_SYSTEM FOREIGN KEY (SYSTEM_ID)
        REFERENCES NAM_IAM_ADMIN.IDINV_SYSTEM_DEFINITIONS(SYSTEM_ID)
);

COMMENT ON TABLE NAM_IAM_ADMIN.IDINV_IMPORT_HISTORY IS 'データ取り込み履歴';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_IMPORT_HISTORY.BATCH_ID IS 'バッチID';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_IMPORT_HISTORY.STATUS IS '処理状態（SUCCESS, ERROR, WARNING）';


