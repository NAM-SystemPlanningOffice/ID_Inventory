-- 組織転出者一時テーブル
-- Python側で判定した出力対象ユーザーの転出元・転出先情報を格納
CREATE TABLE NAM_IAM_ADMIN.IDINV_W_TENSHUTU_TEMP (
    USER_CD VARCHAR2(50) NOT NULL,
    USER_NAME VARCHAR2(200),
    IDO_DATE DATE NOT NULL,
    BEFORE_ORG VARCHAR2(4000),  -- 転出元組織（改行区切り）
    AFTER_ORG VARCHAR2(4000),   -- 転出先組織（改行区切り）
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT IDINV_PK_TENSHUTU_TEMP PRIMARY KEY (USER_CD, IDO_DATE)
);

COMMENT ON TABLE NAM_IAM_ADMIN.IDINV_W_TENSHUTU_TEMP IS '組織転出者一時テーブル（出力処理用）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_W_TENSHUTU_TEMP.USER_CD IS 'ユーザーCD';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_W_TENSHUTU_TEMP.USER_NAME IS 'ユーザー名';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_W_TENSHUTU_TEMP.IDO_DATE IS '異動日';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_W_TENSHUTU_TEMP.BEFORE_ORG IS '転出元組織（改行区切り）';
COMMENT ON COLUMN NAM_IAM_ADMIN.IDINV_W_TENSHUTU_TEMP.AFTER_ORG IS '転出後組織（改行区切り）';
